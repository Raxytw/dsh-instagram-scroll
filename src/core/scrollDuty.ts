function detectAigcPost(caption: string = '', username: string = ''): string | null {
  const textLower = `${caption || ''} ${username || ''}`.toLowerCase()
  for (const kw of AIGC_REJECT_KEYWORDS) {
    if (kw && textLower.includes(kw.toLowerCase())) {
      return kw
    }
  }
  const aigcTagRegex = /#(aiart|aivideo|aianimation|aigenerated|midjourney|stablediffusion|sora|runwayml|klingai|pikaart|aigirl|aigc|ai繪圖|ai動畫|ai影片|ai生成)/i
  const m = textLower.match(aigcTagRegex)
  if (m) return m[0]
  return null
}

